const express = require('express');
const http = require('http');
const { WebSocketServer } = require('ws');
const cors = require('cors');
const path = require('path');
require('dotenv').config();

const app = express();
const server = http.createServer(app);
const wss = new WebSocketServer({ server });

const PORT = process.env.PORT || 3000;
const VAPI_SECRET = process.env.VAPI_SECRET_TOKEN;

app.use(cors());
app.use(express.json({ limit: '10mb' }));
app.use(express.static(path.join(__dirname, 'public')));

// In-memory call store: callId -> Call Details
const callStore = new Map();

function broadcast(event, data) {
  const payload = JSON.stringify({ event, data });
  wss.clients.forEach((client) => {
    if (client.readyState === 1) {
      client.send(payload);
    }
  });
}

wss.on('connection', (ws) => {
  ws.send(JSON.stringify({
    event: 'INIT_STATE',
    data: Array.from(callStore.values())
  }));
});

app.post('/webhook/vapi', (req, res) => {
  if (VAPI_SECRET && req.headers['x-vapi-secret'] !== VAPI_SECRET) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  const { message } = req.body;
  if (!message || !message.call) {
    return res.status(200).json({ received: true });
  }

  const call = message.call;
  const callId = call.id;
  const now = new Date().toISOString();

  // Retrieve existing record or create baseline
  let record = callStore.get(callId) || {
    id: callId,
    status: call.status || 'in-progress',
    customerNumber: call.customer?.number || 'Unknown',
    assistantId: call.assistantId || 'Assistant',
    startedAt: call.startedAt || now,
    updatedAt: now,
    structuredData: {},
    lineItems: []
  };

  switch (message.type) {
    case 'status-update':
      record.status = call.status;
      record.updatedAt = now;
      
      // Pull structured data if available in intermediate payloads
      if (message.artifact?.structuredData) {
        record.structuredData = { ...record.structuredData, ...message.artifact.structuredData };
      }
      callStore.set(callId, record);
      broadcast('CALL_UPDATED', record);
      break;

    case 'tool-calls':
      // Extract structured items sent via function/tool calls during runtime
      if (Array.isArray(message.toolCalls)) {
        message.toolCalls.forEach((tool) => {
          try {
            const args = typeof tool.function?.arguments === 'string' 
              ? JSON.parse(tool.function.arguments) 
              : tool.function?.arguments;

            if (args) {
              // Check if args contain line items/products or generic structured data
              if (args.line_items || args.items) {
                record.lineItems = [...record.lineItems, ...(args.line_items || args.items)];
              }
              record.structuredData = { ...record.structuredData, ...args };
            }
          } catch (e) {
            console.error('Failed to parse tool call args', e);
          }
        });
      }
      record.updatedAt = now;
      callStore.set(callId, record);
      broadcast('CALL_UPDATED', record);
      break;

    case 'end-of-call-report':
      record.status = 'ended';
      record.updatedAt = now;
      record.endedReason = message.endedReason || 'completed';

      // Capture final structured outputs generated by Vapi
      const finalOutputs = message.analysis?.structuredData || message.artifact?.structuredData || message.structuredData;
      if (finalOutputs) {
        record.structuredData = { ...record.structuredData, ...finalOutputs };

        // Pull line items if structured schema output contains items
        if (finalOutputs.line_items || finalOutputs.items) {
          record.lineItems = finalOutputs.line_items || finalOutputs.items;
        }
      }

      callStore.set(callId, record);
      broadcast('CALL_UPDATED', record);
      break;
  }

  return res.status(200).json({ success: true });
});

app.get('/health', (req, res) => {
  res.status(200).json({ status: 'healthy', activeCalls: callStore.size });
});

server.listen(PORT, '0.0.0.0', () => {
  console.log(`Server running on port ${PORT}`);
});